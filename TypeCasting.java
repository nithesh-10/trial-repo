class TypeCasting{
	public static void main(String[] args){
		int n=10;
		double d= (double) n;
		double d2=n;
		System.out.println(d);
		System.out.println(d2);

		double e=19.9;
		int n1=(int) e;
		System.out.println(n1);

		int n2=10;
		long l1= (long) n2;
		long l2=n;
		System.out.println(l1);
		System.out.println(l2);

	}
}

		